#!/usr/bin/env python3
"""Regenerate INDEX.md from the YAML-ish headers in recipes/*.md (stdlib only)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPES = ROOT / "recipes"


def parse_header(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    meta = {}
    for line in text[3:end].splitlines():
        if ":" not in line or line.lstrip().startswith("#"):
            continue
        key, _, val = line.partition(":")
        val = val.split("  #")[0].strip()
        if val.startswith("[") and val.endswith("]"):
            val = [v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip()]
        meta[key.strip()] = val
    return meta


def main():
    rows = []
    for f in sorted(RECIPES.glob("*.md")):
        m = parse_header(f.read_text(encoding="utf-8"))
        if m.get("status") == "retired":
            continue
        rows.append((m, f.name))
    rows.sort(key=lambda r: ((r[0].get("course") or "zz"), (r[0].get("title") or r[1]).lower()))

    out = ["# Recipe Index", "", f"_{len(rows)} recipes. Generated by scripts/build_index.py — do not edit._", ""]
    current = None
    for m, name in rows:
        course = m.get("course") or "uncategorised"
        if course != current:
            out += ["", f"## {course.capitalize()}", "",
                    "| Recipe | From | Cuisine | Time (min) | Tags | Made |",
                    "|---|---|---|---|---|---|"]
            current = course
        tags = m.get("tags") or []
        tags = ", ".join(tags) if isinstance(tags, list) else tags
        made = "✓" if str(m.get("made", "")).lower() == "true" else ""
        if m.get("rating"):
            made += f" {m['rating']}/5"
        out.append(f"| [{m.get('title') or name}](recipes/{name}) | {m.get('from','')} | {m.get('cuisine','')} | "
                   f"{m.get('total_time','')} | {tags} | {made.strip()} |")
    if not rows:
        out.append("_No recipes yet._")
    (ROOT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"INDEX.md: {len(rows)} recipes")


if __name__ == "__main__":
    main()
